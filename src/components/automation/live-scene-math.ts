export function ew(theta: number, rotation: number) {
  const s = (theta * Math.PI) / 180;
  const r = ((theta + rotation) * Math.PI) / 180;
  return {
    x: 421 * (Math.cos(r) - Math.cos(s)),
    y: 155.4 * (Math.sin(r) - Math.sin(s)),
  };
}

export function ev(theta: number, rotation: number) {
  const s = Math.abs((((theta + rotation - 90) % 360) + 540) % 360 - 180);
  return Math.max(0, 1 - s / 90);
}

export function arcPath(angle: number, yOffset = 0) {
  const start = angle - 15;
  const parts: string[] = [];
  for (let i = 0; i <= 20; i++) {
    const rad = ((start + (30 * i) / 20) * Math.PI) / 180;
    const x = 673.5 + 350.5 * Math.cos(rad);
    const y = 500 + 104.2 * Math.sin(rad) + yOffset;
    parts.push(`${i === 0 ? "M" : "L"}${x.toFixed(2)} ${y.toFixed(2)}`);
  }
  return parts.join("");
}

export function activeStepFromRotation(rotation: number) {
  let best = 0;
  let bestAmt = -1;
  for (const icon of FLOATING_ICONS) {
    const amt = ev(icon.theta, rotation);
    if (amt > bestAmt) {
      bestAmt = amt;
      best = icon.step;
    }
  }
  return best;
}

export function rotationForStep(step: number) {
  return STEP_ROTATIONS[step] ?? 180;
}

export function tileInk(theta: number, rotation: number) {
  const n = Math.round(178 * (1 - ev(theta, rotation)));
  return `rgb(${n} ${n} ${n})`;
}

